//! Source-engine launch-argument assembly.
//!
//! Mirrors the original launcher's argument construction so the resulting
//! command line is byte-compatible with what the engine expects.

use std::fmt::Write as _;

/// Screen mode handed to the engine.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Mode {
    pub width: u32,
    pub height: u32,
    pub fullscreen: bool,
}

impl Mode {
    pub fn new(width: u32, height: u32, fullscreen: bool) -> Self {
        Self {
            width,
            height,
            fullscreen,
        }
    }
}

/// Renderer selection: OpenGL ES (default) or native Vulkan.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Renderer {
    OpenGlEs,
    Vulkan,
}

impl Renderer {
    /// The token the launcher writes into `launch_args` to request Vulkan.
    pub const VULKAN_TOKEN: &'static str = "-sourcevr_native_vulkan";

    pub fn from_launch_args(args: &str) -> Self {
        if args
            .split_whitespace()
            .any(|t| t.eq_ignore_ascii_case(Self::VULKAN_TOKEN))
        {
            Renderer::Vulkan
        } else {
            Renderer::OpenGlEs
        }
    }
}

/// User-supplied extras parsed from the `launch_args` setting.
///
/// Kept verbatim so unknown flags pass through to the engine untouched.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Extras {
    pub tokens: Vec<String>,
}

impl Extras {
    pub fn parse(raw: &str) -> Self {
        Self {
            tokens: raw.split_whitespace().map(str::to_owned).collect(),
        }
    }

    pub fn is_empty(&self) -> bool {
        self.tokens.is_empty()
    }

    /// Returns the map name from a `+map <name>` pair, if present.
    pub fn map(&self) -> Option<&str> {
        self.pair("+map")
    }

    /// Returns the server address from a `+connect <host:port>` pair, if present.
    pub fn connect(&self) -> Option<&str> {
        self.pair("+connect")
    }

    fn pair(&self, key: &str) -> Option<&str> {
        let idx = self
            .tokens
            .iter()
            .position(|t| t.eq_ignore_ascii_case(key))?;
        self.tokens.get(idx + 1).map(String::as_str)
    }

    /// Removes `+map`, `+load` and `+connect` pairs — used when the launcher
    /// must not override a workshop-driven start.
    pub fn without_start_commands(&self) -> Self {
        let mut out = Vec::new();
        let mut skip = false;
        for token in &self.tokens {
            if skip {
                if token.starts_with('+') || token.starts_with('-') {
                    skip = false;
                } else {
                    continue;
                }
            }
            if ["+map", "+load", "+connect"]
                .iter()
                .any(|k| token.eq_ignore_ascii_case(k))
            {
                skip = true;
                continue;
            }
            if token.eq_ignore_ascii_case("-nocustom") {
                continue;
            }
            out.push(token.clone());
        }
        Self { tokens: out }
    }
}

/// Heap size in megabytes, clamped the same way the launcher does.
pub fn heap_size_mb(avail_mem_bytes: u64) -> u32 {
    let avail_mb = (avail_mem_bytes / 1_048_576) as i64;
    (avail_mb - 768).clamp(256, 1536) as u32
}

/// Builds the engine command line.
///
/// `renderer` is resolved separately so a Vulkan request can be declined
/// (unsupported device, previous crash marker) without rewriting user extras.
pub fn build(
    game_dir: &str,
    mode: Mode,
    heap_mb: u32,
    renderer: Renderer,
    extras: &Extras,
) -> Vec<String> {
    let mut args: Vec<String> = vec![
        "-game".into(),
        game_dir.into(),
        "-steam".into(),
        "-nouserclip".into(),
        "-novid".into(),
        "-hushasserts".into(),
        "-mobile".into(),
        "-heapsize".into(),
        heap_mb.to_string(),
    ];

    if mode.fullscreen {
        args.push("-fullscreen".into());
    }
    args.push("-w".into());
    args.push(mode.width.to_string());
    args.push("-h".into());
    args.push(mode.height.to_string());

    args.push("+exec".into());
    args.push("android_settings.cfg".into());

    if renderer == Renderer::Vulkan {
        args.push(Renderer::VULKAN_TOKEN.into());
    }

    // User extras come last so they can override defaults.
    args.extend(extras.tokens.iter().cloned());
    args
}

/// Renders the generated `android_settings.cfg` content.
pub fn config(
    fps_max: u32,
    touch_opacity_percent: u32,
    show_joystick: bool,
    sprint_toggle: bool,
    ui_scale_percent: u32,
) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// Generated by OpenGDroid.");
    let _ = writeln!(out, "fps_max {fps_max}");
    let _ = writeln!(
        out,
        "touch_opacity {:.2}",
        touch_opacity_percent.min(100) as f32 / 100.0
    );
    let _ = writeln!(out, "touch_show_joystick {}", u8::from(show_joystick));
    let _ = writeln!(out, "touch_sprint_toggle {}", u8::from(sprint_toggle));
    let _ = writeln!(
        out,
        "vgui_ui_scale {:.2}",
        ui_scale_percent.clamp(50, 200) as f32 / 100.0
    );
    let _ = writeln!(out, "vr_mainmenu 0");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn vulkan_token_detected() {
        assert_eq!(
            Renderer::from_launch_args("-sourcevr_native_vulkan +map gm_construct"),
            Renderer::Vulkan
        );
        assert_eq!(
            Renderer::from_launch_args("+map gm_construct"),
            Renderer::OpenGlEs
        );
    }

    #[test]
    fn heap_is_clamped() {
        assert_eq!(heap_size_mb(0), 256);
        assert_eq!(heap_size_mb(2_147_483_648), 1280);
        assert_eq!(heap_size_mb(8 * 1_073_741_824), 1536);
    }

    #[test]
    fn extras_parse_map_and_connect() {
        let e = Extras::parse("-sourcevr_native_vulkan +map gm_construct +connect 1.2.3.4:27015");
        assert_eq!(e.map(), Some("gm_construct"));
        assert_eq!(e.connect(), Some("1.2.3.4:27015"));
    }

    #[test]
    fn start_commands_can_be_stripped() {
        let e = Extras::parse("+map gm_flatgrass -nocustom +fps_max 60");
        let stripped = e.without_start_commands();
        assert_eq!(stripped.map(), None);
        assert!(stripped.tokens.contains(&"+fps_max".to_string()));
        assert!(!stripped.tokens.contains(&"-nocustom".to_string()));
    }

    #[test]
    fn build_includes_renderer_and_mode() {
        let args = build(
            "garrysmod",
            Mode::new(1520, 720, true),
            512,
            Renderer::Vulkan,
            &Extras::parse("+map gm_construct"),
        );
        let joined = args.join(" ");
        assert!(joined.contains("-game garrysmod"));
        assert!(joined.contains("-fullscreen"));
        assert!(joined.contains("-w 1520"));
        assert!(joined.contains("-h 720"));
        assert!(joined.contains("-sourcevr_native_vulkan"));
        assert!(joined.ends_with("+map gm_construct"));
    }

    #[test]
    fn config_has_expected_keys() {
        let cfg = config(60, 50, true, false, 100);
        assert!(cfg.contains("fps_max 60"));
        assert!(cfg.contains("touch_opacity 0.50"));
        assert!(cfg.contains("touch_show_joystick 1"));
        assert!(cfg.contains("vgui_ui_scale 1.00"));
    }
}
